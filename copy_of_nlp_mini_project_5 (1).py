# Movie Review Sentiment Analysis

# Task 1: Install and Import Libraries
"""

import pandas as pd
import re
from datasets import load_dataset
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report
from sklearn.metrics import confusion_matrix

"""# Task 2: Load Real Dataset"""

dataset = load_dataset("stanfordnlp/imdb")

train_df = pd.DataFrame(dataset["train"]).sample(5000, random_state=42)
test_df = pd.DataFrame(dataset["test"]).sample(1000, random_state=42)

"""# Task 3: Explore the Data

"""

print("Train Shape:", train_df.shape)

print("\nLabel Distribution")
print(train_df["label"].value_counts())

train_df.head()

"""# Task 4: Build a Text Preprocessing Function

"""

# Text preprocessing
def preprocess(text):

    # Convert text to lowercase
    text = text.lower()

    # Remove URLs
    text = re.sub(r'http\S+|www\S+', '', text)

    # Remove punctuation
    text = re.sub(r'[^\w\s]', '', text)

    # Fix extra spaces
    text = re.sub(r'\s+', ' ', text).strip()

    return text

"""# Task 5: Apply Preprocessing

"""

# TODO:
# Create cleaned text columns
train_df["clean_text"] = train_df["text"].apply(preprocess)
test_df["clean_text"] = test_df["text"].apply(preprocess)

"""# Task 6: Train/Test Variables

"""

# Define features and labels
X_train = train_df["clean_text"]
X_test = test_df["clean_text"]

y_train = train_df["label"]
y_test = test_df["label"]

"""# Task 7: TF-IDF Vectorization

"""

# IMPORTANT:
# Fit ONLY on training data

# Create TfidfVectorizer
vectorizer = TfidfVectorizer(max_features=5000)

# Fit on training data
vectorizer.fit(X_train)

# Transform training data
X_train_tfidf = vectorizer.transform(X_train)

# Transform testing data
X_test_tfidf = vectorizer.transform(X_test)

"""# Task 8: Train Sentiment Classifier

"""

# TODO:
# Create Logistic Regression model
model = LogisticRegression(max_iter=1000)

# Train model
model.fit(X_train_tfidf, y_train)

"""# Task 9: Predictions

"""

# Predictions
y_pred = model.predict(X_test_tfidf)

"""# Task 10: Evaluation

"""

# Print classification report
print("Classification Report:")
print(classification_report(y_test, y_pred))

# Print confusion matrix
print("\nConfusion Matrix:")
print(confusion_matrix(y_test, y_pred, labels=[0, 1]))

"""# Task 11: Custom Review Testing

"""

custom_review = """
This movie was fantastic.
The acting was amazing and the story was excellent.
"""

clean_review = preprocess(custom_review)

# Vectorize review
review_vector = vectorizer.transform([clean_review])

# Predict sentiment
prediction = model.predict(review_vector)

# Print result
if prediction[0] == 1:
    print("Positive")
else:
    print("Negative")